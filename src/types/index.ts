export interface VideoMetadata {
  videoId: string;
  url: string;
  title: string;
  channelName: string;
  channelUrl: string;
  viewCount: number;
  formattedViews: string;
  likeCount: string;
  durationSeconds: number;
  formattedDuration: string;
  uploadDate: string;
  description: string;
  thumbnailUrl: string;
  channelAvatarUrl?: string;
  isShort: boolean;
}

export interface TranscriptSegment {
  start: number;       // Start time in seconds (e.g. 12.45)
  duration: number;    // Duration in seconds (e.g. 3.20)
  timestamp: string;   // Formatted string (e.g. "00:12" or "01:23:45")
  text: string;        // Cleaned text content
}

export interface CaptionTrackInfo {
  languageCode: string;
  name: string;
  isAutoGenerated: boolean;
  baseUrl: string;
}

export interface TranscriptData {
  available: boolean;
  selectedLanguage: string;
  availableTracks: CaptionTrackInfo[];
  segments: TranscriptSegment[];
  fullText: string;
  wordCount: number;
  error?: string;
}

export interface ExtractorResult {
  videoId: string;
  metadata: VideoMetadata;
  transcript: TranscriptData;
  extractedAt: string;
}

export interface UserPreferences {
  autoExtract: boolean;
  preferredLanguage: string;
  panelMinimized: boolean;
  theme: 'dark' | 'light' | 'auto';
}

export interface BridgeMessagePayload {
  videoId: string;
  playerResponse?: any;
}
