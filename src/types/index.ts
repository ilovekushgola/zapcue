export interface SubscriberInfo {
  count?: number;
  displayText: string;
  status: 'available' | 'rounded' | 'hidden' | 'unavailable';
}

export interface VideoMetadata {
  videoId: string;
  url: string;
  title: string;
  channelName: string;
  channelUrl: string;
  viewCount: number;
  formattedViews: string;
  likeCount: string;
  durationSeconds: number;
  formattedDuration: string;
  uploadDate: string;
  description: string;
  thumbnailUrl: string;
  channelAvatarUrl?: string;
  subscriberInfo?: SubscriberInfo;
  isShort: boolean;
}

export interface ChapterItem {
  title: string;
  startSeconds: number;
  startTimestamp: string;
  endSeconds?: number;
  source: 'player_markers' | 'description_timestamps';
}

export interface ChapterData {
  available: boolean;
  items: ChapterItem[];
}

export interface CommentAuthor {
  displayName: string;
  channelUrl?: string;
  avatarUrl?: string;
}

export interface CommentItem {
  id: string;
  videoId: string;
  text: string;
  author: CommentAuthor;
  publishedAt?: string;
  likeCount?: string;
  replyCount?: number;
  isOwner?: boolean;
  isPinned?: boolean;
  replies?: CommentItem[];
}

export interface CommentData {
  available: boolean;
  status: 'complete' | 'partial' | 'loading' | 'unavailable' | 'failed' | 'not_requested';
  sortOrder: 'top' | 'newest';
  requestedLimit: number;
  extractedCount: number;
  threads: CommentItem[];
  error?: string;
}

export interface TranscriptSegment {
  start: number;       // Start time in seconds (e.g. 12.45)
  duration: number;    // Duration in seconds (e.g. 3.20)
  timestamp: string;   // Formatted string (e.g. "00:12" or "01:23:45")
  text: string;        // Cleaned text content
}

export interface CaptionTrackInfo {
  languageCode: string;
  name: string;
  isAutoGenerated: boolean;
  baseUrl: string;
}

export interface TranscriptData {
  available: boolean;
  selectedLanguage: string;
  availableTracks: CaptionTrackInfo[];
  segments: TranscriptSegment[];
  fullText: string;
  wordCount: number;
  error?: string;
}

export interface ExtractorResult {
  videoId: string;
  metadata: VideoMetadata;
  transcript: TranscriptData;
  chapters?: ChapterData;
  comments?: CommentData;
  extractedAt: string;
}

export interface ZapcueSettings {
  schemaVersion: number;
  // General
  autoExtract: boolean;
  preferredLanguage: string;
  theme: 'auto' | 'dark' | 'light';
  // Panel layout
  showThumbnailPreview: boolean;
  defaultTranscriptExpanded: boolean;
  defaultChaptersExpanded: boolean;
  defaultCommentsExpanded: boolean;
  // Comments
  autoExtractComments: boolean;
  commentSortOrder: 'top' | 'newest';
  commentLimit: number;
  includeCommentReplies: boolean;
  includeCommentsInCopy: boolean;
  // Export
  exportIncludeChapters: boolean;
  exportIncludeImages: boolean;
  exportIncludeComments: boolean;
}

export interface UserPreferences {
  autoExtract: boolean;
  preferredLanguage: string;
  panelMinimized: boolean;
  theme: 'dark' | 'light' | 'auto';
}

export interface BridgeMessagePayload {
  videoId: string;
  playerResponse?: any;
}
